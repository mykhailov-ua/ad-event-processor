def _build_report_from_def(defn: dict[str, object]) -> MilestoneSpec:
    key = str(defn["key"])
    suffix = str(defn["suffix"])
    return make_report(
        f"ADMIN_REPORT_MILESTONE_{suffix}.md",
        f"admin_report_{key.replace('-', '_')}",
        str(defn["route"]),
        key,
        str(defn["api"]),
        str(defn["summary"]),
        gap=bool(defn.get("gap", False)),
        columns=list(defn.get("columns", [])),
        column_source=str(defn.get("column_source", "handler")),
        schema_ref=str(defn.get("schema_ref", "")),
        operation_id=str(defn.get("operation_id", "")),
        url_params=defn.get("url_params"),  # type: ignore[arg-type]
        content_kind=str(defn.get("content_kind", "grid")),
        live=str(defn.get("live", "false")),
        buyer=bool(defn.get("buyer", False)),
        legacy=str(defn.get("legacy", "")),
        fetch_path=str(defn.get("fetch_path", "")),
        export_supported=bool(defn.get("export_supported", False)),
        compare_supported=bool(defn.get("compare_supported", True)),
        grid_cols=str(defn.get("grid_cols", "")),
        extra_pitfalls=defn.get("extra_pitfalls"),  # type: ignore[arg-type]
        forbidden_extra=defn.get("forbidden_extra"),  # type: ignore[arg-type]
    )



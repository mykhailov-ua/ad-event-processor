def _report_fetch_example(api_path: str, params: list[UrlParam]) -> str:
    query_parts: list[str] = []
    for param in params:
        if param.name == "customer_id":
            query_parts.append("customer_id={uuid}")
        elif param.name == "from":
            query_parts.append("from={iso}")
        elif param.name == "to":
            query_parts.append("to={iso}")
        elif param.name == "click_id":
            query_parts.append("click_id={click_id}")
        elif param.name == "campaign_id" and param.notes.startswith("required"):
            query_parts.append("campaign_id={uuid}")
        elif param.name == "toggle_field":
            query_parts.append("toggle_field=silent_reject_enabled")
    return f"{api_path}?{'&'.join(query_parts)}" if query_parts else api_path



        blocks="—",
        pattern="dashboard",
        summary=f"Dashboard: {title}.",
        route=route,
        apis=api,
        operation_id=operation_id,
        schema_ref=schema_ref,
        handler=handler,
        domain=domain,
        legacy=legacy,
        permission=permission,
        in_scope=in_scope,

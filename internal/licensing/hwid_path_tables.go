func decodeHWIDPath(pathID uint8, suffix, dst []byte) int {
	if int(pathID) >= len(hwidPathEnc) {
		return 0
	}
	enc := hwidPathEnc[pathID]
	if len(enc)+len(suffix) > len(dst) {
		return 0
	}
	for i, b := range enc {
		dst[i] = b ^ hwidPathXORMask
	}
	n := len(enc)
	if len(suffix) > 0 {
		copy(dst[n:], suffix)
		n += len(suffix)
	}
	return n
}

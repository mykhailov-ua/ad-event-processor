package verify

import "crypto/ed25519"

var decoyPubKeyMasked = [32]byte{
	0x2c, 0x91, 0x44, 0xa8, 0x73, 0x1e, 0x5b, 0xc4,
	0x09, 0xf6, 0x33, 0x88, 0x41, 0xde, 0x12, 0x67,
	0xb5, 0x08, 0xec, 0x3a, 0x71, 0x25, 0x9d, 0x50,
	0x6f, 0x14, 0xcb, 0x7e, 0x03, 0x98, 0xe1, 0x4d,
}

var decoyPubKeyMask = [32]byte{
	0x63, 0xfe, 0x2d, 0x11, 0x16, 0xab, 0x3f, 0x99,
	0x48, 0x85, 0x5e, 0xed, 0x24, 0xb1, 0x7c, 0x02,
	0xd0, 0x67, 0x8a, 0x55, 0x1e, 0x4c, 0xf3, 0x39,
	0x0a, 0xbe, 0x92, 0x17, 0x6d, 0xc4, 0x80, 0x22,
}

func decoyEmbeddedPublicKey() ed25519.PublicKey {
	var raw [ed25519.PublicKeySize]byte
	for i := range 32 {
		raw[i] = decoyPubKeyMasked[i] ^ decoyPubKeyMask[i]
	}
	return ed25519.PublicKey(raw[:])
}

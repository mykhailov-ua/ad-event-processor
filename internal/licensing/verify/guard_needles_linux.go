package verify

func guardSuspiciousMapNeedles() [][]byte {
	enc := [][]byte{
		{0x55, 0x41, 0x5a, 0x5a, 0x52},
		{0x54, 0x57, 0x56},
		{0x5f, 0x5f, 0x56, 0x57},
		{0x5a, 0x41, 0x5a, 0x5a, 0x52},
		{0x5a, 0x41, 0x5a, 0x5a, 0x5a, 0x5c, 0x5e},
		{0x5f, 0x5a, 0x5d, 0x59, 0x56, 0x50, 0x47, 0x5c, 0x41},
		{0x54, 0x46, 0x5e, 0x1e, 0x59, 0x40},
		{0x55, 0x41, 0x5a, 0x57, 0x52, 0x1e, 0x52, 0x54, 0x56, 0x5d, 0x47},
		{0x55, 0x41, 0x5a, 0x57, 0x52, 0x1e, 0x54, 0x5b, 0x56, 0x5d, 0x47},
	}
	out := make([][]byte, len(enc))
	for i, row := range enc {
		dec := make([]byte, len(row))
		for j, b := range row {
			dec[j] = b ^ 0x33
		}
		out[i] = dec
	}
	return out
}
